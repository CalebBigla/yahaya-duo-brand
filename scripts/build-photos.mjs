// Generates responsive images for the public site from originals in src/assets/photos.
//
//   npm run images
//
// For every photo in src/assets/photos (jpg, jpeg, png, webp, tif) it writes AVIF, WebP
// and JPEG files at 640/960/1440/2048 px wide into src/assets/photos/generated/,
// never enlarging beyond the original, plus src/assets/photos/generated/index.ts which
// exports one ResponsiveSource per photo (keyed by file name) for <ResponsiveImage>.
//
// Run it locally when photos change and commit the output. Deploys never process
// images, so builds on Render stay fast and within memory.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const WIDTHS = [640, 960, 1440, 2048];
const root = path.resolve('src/assets/photos');
const out = path.join(root, 'generated');
fs.mkdirSync(out, { recursive: true });

const slug = (name) =>
  name
    .replace(/\.[^.]+$/, '')
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, '-');
const ident = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');

const originals = fs
  .readdirSync(root)
  .filter((f) => /\.(jpe?g|png|webp|tiff?)$/i.test(f))
  .sort();

if (originals.length === 0) {
  console.log('No photos in src/assets/photos yet. Add originals (2400px+ on the long edge) and run again.');
}

const imports = [];
const entries = [];
for (const file of originals) {
  const name = slug(file);
  const id = ident(name);
  const input = sharp(path.join(root, file)).rotate();
  const meta = await input.metadata();
  const width = meta.autoOrient?.width ?? meta.width;
  const height = meta.autoOrient?.height ?? meta.height;
  if (Math.max(width, height) < 2400) {
    console.warn(`  ! ${file} is ${width}x${height}; 2400px+ on the long edge is recommended.`);
  }
  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, width)))];
  const sets = { avif: [], webp: [], jpeg: [] };
  for (const w of widths) {
    const resized = sharp(path.join(root, file)).rotate().resize({ width: w, withoutEnlargement: true });
    for (const [format, options] of [
      ['avif', { quality: 50, effort: 4 }],
      ['webp', { quality: 75, effort: 5 }],
      ['jpeg', { quality: 78, mozjpeg: true, progressive: true }],
    ]) {
      const ext = format === 'jpeg' ? 'jpg' : format;
      const fileName = `${name}-${w}.${ext}`;
      await resized.clone()[format](options).toFile(path.join(out, fileName));
      const varName = `${id}_${w}_${ext}`;
      imports.push(`import ${varName} from "./${fileName}";`);
      sets[format].push(`\${${varName}} ${w}w`);
    }
  }
  const largestJpeg = `${id}_${widths.at(-1)}_jpg`;
  entries.push(
    `  ${JSON.stringify(name)}: {\n` +
      `    fallback: ${largestJpeg},\n` +
      `    avif: \`${sets.avif.join(', ')}\`,\n` +
      `    webp: \`${sets.webp.join(', ')}\`,\n` +
      `    jpeg: \`${sets.jpeg.join(', ')}\`,\n` +
      `    width: ${width},\n    height: ${height},\n` +
      `    alt: "", // TODO: describe this photo\n` +
      `  },`,
  );
  console.log(`  ✓ ${file} -> ${widths.join('/')}px x avif/webp/jpg`);
}

fs.writeFileSync(
  path.join(out, 'index.ts'),
  `// Generated by scripts/build-photos.mjs. Do not edit by hand; run \`npm run images\`.\n` +
    `import type { ResponsiveSource } from "@/components/site/ResponsiveImage";\n` +
    `${imports.join('\n')}\n\n` +
    `export const photos = {\n${entries.join('\n')}\n} satisfies Record<string, ResponsiveSource>;\n`,
);
console.log(`Wrote ${path.relative(process.cwd(), path.join(out, 'index.ts'))} (${originals.length} photo${originals.length === 1 ? '' : 's'}).`);
